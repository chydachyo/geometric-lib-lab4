def area(a, h):
    '''
    Принимает сторону треугольника и его высоту, возвращает площадь.
    
        Параметры:
            a (float): длина стороны треугольника
            h (float): высота, проведенная к этой стороне
            
        Возвращаемое значение:
            area (float): площадь треугольника
            
        Пример вызова:
            area(4, 5)
    '''
    return a * h / 2

def perimeter(a, b, c):
    '''
    Принимает длины трех сторон треугольника и возвращает его периметр.
    
        Параметры:
            a (float): первая сторона треугольника
            b (float): вторая сторона треугольника
            c (float): третья сторона треугольника
            
        Возвращаемое значение:
            perimeter (float): периметр треугольника
            
        Пример вызова:
            perimeter(3, 4, 5)
    '''
    return a + b + c