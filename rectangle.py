def area(a, b):
    '''
    Принимает длины двух сторон прямоугольника и возвращает его площадь.
    
        Параметры:
            a (float): первая сторона прямоугольника
            b (float): вторая сторона прямоугольника
            
        Возвращаемое значение:
            area (float): площадь прямоугольника
            
        Пример вызова:
            area(4, 5)
    '''
    return a * b

def perimeter(a, b):
    '''
    Принимает длины двух сторон прямоугольника и возвращает его периметр.
    
        Параметры:
            a (float): первая сторона прямоугольника
            b (float): вторая сторона прямоугольника
        
        Возвращаемое значение:
            perimeter (float): периметр прямоугольника
        
        Пример вызова:
            perimeter(4, 5)
    '''
    return 2 * (a+b)