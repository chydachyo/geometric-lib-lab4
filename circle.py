import math

def area(r):
    '''
    Принимает радиус круга и возвращает его площадь.
    
        Параметры:
            r (float): радиус круга
            
        Возвращаемое значение:
            area (float): площадь круга
            
        Пример вызова:
            area(5)
        '''
    return math.pi * r * r


def perimeter(r):
    '''
    Принимает радиус круга и возвращает длину окружности.
    
        Параметры:
            r (float): радиус круга
            
        Возвращаемое значение:
            perimeter (float): длина окружности
            
        Пример вызова:                                                                          
            perimeter(5)
    '''
    
    return 2 * math.pi * r

